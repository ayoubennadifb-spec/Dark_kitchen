import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';
import { useAuth } from './useAuth';
import { toast } from 'sonner';
import { Json } from '@/integrations/supabase/types';

export interface OrderItem {
  dish_id: string;
  name: string;
  price: number;
  quantity: number;
  special_instructions?: string;
}

export interface Order {
  id: string;
  order_number: string;
  customer_id: string;
  chef_id: string;
  driver_id?: string;
  items: OrderItem[];
  subtotal: number;
  delivery_fee: number;
  service_fee: number;
  total: number;
  status: string;
  payment_status: string;
  delivery_address?: string;
  delivery_city?: string;
  delivery_neighborhood?: string;
  delivery_notes?: string;
  created_at: string;
}

export const useMyOrders = () => {
  const { user } = useAuth();

  return useQuery({
    queryKey: ['my-orders', user?.id],
    queryFn: async () => {
      if (!user) return [];

      const { data, error } = await supabase
        .from('orders')
        .select(`
          *,
          chef_profiles:chef_id (
            id,
            profiles:user_id (full_name)
          )
        `)
        .eq('customer_id', user.id)
        .order('created_at', { ascending: false });

      if (error) throw error;
      return data as unknown as Order[];
    },
    enabled: !!user,
  });
};

export const useOrder = (orderId: string) => {
  return useQuery({
    queryKey: ['order', orderId],
    queryFn: async () => {
      const { data, error } = await supabase
        .from('orders')
        .select(`
          *,
          chef_profiles:chef_id (
            id,
            profiles:user_id (full_name, phone)
          ),
          driver_profiles:driver_id (
            id,
            profiles:user_id (full_name, phone)
          )
        `)
        .eq('id', orderId)
        .maybeSingle();

      if (error) throw error;
      return data as unknown as Order;
    },
    enabled: !!orderId,
  });
};

export interface CreateOrderData {
  items: OrderItem[];
  chefId: string;
  subtotal: number;
  deliveryFee: number;
  serviceFee: number;
  total: number;
  deliveryAddress?: string;
  deliveryCity?: string;
  deliveryNeighborhood?: string;
  deliveryNotes?: string;
  isPickup?: boolean;
}

export const useCreateOrder = () => {
  const queryClient = useQueryClient();
  const { user } = useAuth();

  return useMutation({
    mutationFn: async (orderData: CreateOrderData) => {
      if (!user) throw new Error('Vous devez être connecté');

      const { data, error } = await supabase
        .from('orders')
        .insert({
          customer_id: user.id,
          chef_id: orderData.chefId,
          items: orderData.items as unknown as Json,
          subtotal: orderData.subtotal,
          delivery_fee: orderData.deliveryFee,
          service_fee: orderData.serviceFee,
          total: orderData.total,
          delivery_address: orderData.deliveryAddress,
          delivery_city: orderData.deliveryCity,
          delivery_neighborhood: orderData.deliveryNeighborhood,
          delivery_notes: orderData.deliveryNotes,
          is_pickup: orderData.isPickup || false,
          status: 'pending',
          payment_status: 'pending',
          order_number: '', // Will be generated by trigger
        })
        .select()
        .single();

      if (error) throw error;
      return data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['my-orders'] });
      queryClient.invalidateQueries({ queryKey: ['cart'] });
    },
    onError: (error: Error) => {
      toast.error(error.message);
    },
  });
};

export const useCancelOrder = () => {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async ({ orderId, reason }: { orderId: string; reason?: string }) => {
      const { error } = await supabase
        .from('orders')
        .update({
          status: 'cancelled',
          cancellation_reason: reason,
          cancelled_at: new Date().toISOString(),
        })
        .eq('id', orderId);

      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['my-orders'] });
      toast.success('Commande annulée');
    },
    onError: (error: Error) => {
      toast.error(error.message);
    },
  });
};

// Hook for chefs to get their orders
export const useChefOrders = () => {
  const { user } = useAuth();

  return useQuery({
    queryKey: ['chef-orders', user?.id],
    queryFn: async () => {
      if (!user) return [];

      // First get chef profile id
      const { data: chefProfile } = await supabase
        .from('chef_profiles')
        .select('id')
        .eq('user_id', user.id)
        .maybeSingle();

      if (!chefProfile) return [];

      const { data, error } = await supabase
        .from('orders')
        .select('*')
        .eq('chef_id', chefProfile.id)
        .order('created_at', { ascending: false });

      if (error) throw error;
      return data as unknown as Order[];
    },
    enabled: !!user,
  });
};

export const useUpdateOrderStatus = () => {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async ({ orderId, status }: { orderId: string; status: string }) => {
      const updateData: Record<string, any> = { status };

      // Set timestamps based on status
      if (status === 'confirmed') updateData.confirmed_at = new Date().toISOString();
      if (status === 'ready') updateData.ready_at = new Date().toISOString();
      if (status === 'picked_up') updateData.picked_up_at = new Date().toISOString();
      if (status === 'delivered') updateData.delivered_at = new Date().toISOString();

      const { error } = await supabase
        .from('orders')
        .update(updateData)
        .eq('id', orderId);

      if (error) throw error;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['chef-orders'] });
      queryClient.invalidateQueries({ queryKey: ['my-orders'] });
      toast.success('Statut mis à jour');
    },
    onError: (error: Error) => {
      toast.error(error.message);
    },
  });
};
